def seed_database(db) -> None:
    """
    Populate the in-memory SQLite database with demo categories and products.
    Safe to call multiple times (idempotent via existence check).
    """
    from app.models.category import Category
    from app.models.product import Product
    from app.models.user import User
    from app.core.security import get_password_hash

    # Already seeded?
    if db.query(Category).count() > 0:
        return

    # ── Categories ─────────────────────────────────────────────────────────
    cat_map: dict[str, int] = {}
    for cat_data in CATEGORIES:
        cat = Category(name=cat_data["name"], description=cat_data["description"])
        db.add(cat)
        db.flush()
        cat_map[cat_data["name"]] = cat.id

    # ── Demo admin user ────────────────────────────────────────────────────
    admin = User(
        name="Demo Admin",
        email="admin@greencart.demo",
        password_hash=get_password_hash("Admin@123"),
        role="admin",
    )
    db.add(admin)

    # ── Demo regular user ──────────────────────────────────────────────────
    user = User(
        name="Priya Sharma",
        email="priya@greencart.demo",
        password_hash=get_password_hash("User@123"),
        role="user",
    )
    db.add(user)

    # ── Products ───────────────────────────────────────────────────────────
    for p in PRODUCTS:
        cat_id = cat_map.get(p["category"])
        if cat_id is None:
            continue  # skip if category missing
        product = Product(
            name=p["name"],
            brand=p["brand"],
            category_id=cat_id,
            description=p.get("description"),
            price=p["price"],
            currency=p.get("currency", "INR"),
            image_url=p.get("image_url"),
            materials=p.get("materials"),
            is_sustainable=p.get("is_sustainable", False),
            durability_score=p.get("durability_score"),
            packaging_score=p.get("packaging_score"),
            repairability_score=p.get("repairability_score"),
            source_verification_status=p.get("source_verification_status", "unverified"),
        )
        db.add(product)

    db.commit()
    print(f"[GreenCart] Demo database seeded: {len(CATEGORIES)} categories, {len(PRODUCTS)} products.")
